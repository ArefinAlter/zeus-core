//! JSON Schema generation for the types of this crate.
//!
//! The *normative* schemas are the hand-written files in `docs/spec/schema` of the `zeus` repository
//! (copied to `spec-fixtures/schema` for tests). The schemas generated here describe what the Rust
//! types actually accept and emit; `examples/gen_schemas.rs` writes them to `schemas/` and the test
//! `schema_drift` keeps the committed copy current.

use schemars::generate::SchemaSettings;
use schemars::{JsonSchema, SchemaGenerator};
use serde_json::{Map, Value};

use crate::{
    Approval, ErrorEnvelope, Event, Job, JobSpec, JobSummary, ProbeResult, Progress, Segment,
    SessionGrant,
};

/// `$id` of the bundled schema.
pub const BUNDLE_ID: &str = "https://zeus.invalid/schema/zeus-types.generated";

fn add<T: JsonSchema>(generator: &mut SchemaGenerator) {
    let _ = generator.subschema_for::<T>();
}

/// The bundled schema of every public entity: a JSON Schema 2020-12 document whose `$defs` hold one
/// definition per type (ids and timestamps are inlined as constrained strings).
#[must_use]
pub fn bundle() -> Value {
    let mut generator = SchemaGenerator::new(SchemaSettings::draft2020_12());
    add::<Job>(&mut generator);
    add::<JobSpec>(&mut generator);
    add::<JobSummary>(&mut generator);
    add::<ProbeResult>(&mut generator);
    add::<Progress>(&mut generator);
    add::<Segment>(&mut generator);
    add::<SessionGrant>(&mut generator);
    add::<Approval>(&mut generator);
    add::<Event>(&mut generator);
    add::<ErrorEnvelope>(&mut generator);
    let defs = generator.take_definitions(true);

    let mut root = Map::new();
    root.insert(
        "$schema".into(),
        Value::String("https://json-schema.org/draft/2020-12/schema".into()),
    );
    root.insert("$id".into(), Value::String(BUNDLE_ID.into()));
    root.insert(
        "title".into(),
        Value::String("Zeus domain types (generated from the Rust definitions)".into()),
    );
    root.insert(
        "description".into(),
        Value::String(
            "Generated by zeus-types; not normative. The normative schemas are docs/spec/schema in the zeus repository.".into(),
        ),
    );
    root.insert("$defs".into(), Value::Object(defs));
    Value::Object(root)
}
